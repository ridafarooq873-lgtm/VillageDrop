import { useCallback, useEffect, useState } from 'react'
import client from '../api/client.js'
import { useRealtimeTick } from '../context/SocketContext.jsx'
import Spinner from '../components/Spinner.jsx'
import { formatPKR } from '../utils/currency.js'

const PAYOUT_PILL = {
  pending: 'pill-amber',
  processing: 'pill-blue',
  paid: 'pill-green',
  failed: 'pill-red',
  cancelled: 'pill-muted',
}

const fmtDate = (d) => (d ? new Date(d).toLocaleDateString('en-PK') : '—')

function Stat({ value, label, tone }) {
  return (
    <div className="stat">
      <span className={`stat-value ${tone ? `tone-${tone}` : ''}`}>{value}</span>
      <span className="stat-label">{label}</span>
    </div>
  )
}

export default function Earnings() {
  const [data, setData] = useState(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')
  const tick = useRealtimeTick('delivery:update', 'order:update')

  const load = useCallback(async () => {
    setLoading(true)
    setError('')
    try {
      const { data } = await client.get('/riders/me/earnings')
      setData(data)
    } catch (err) {
      setError(err.message)
    } finally {
      setLoading(false)
    }
  }, [])

  useEffect(() => {
    load()
  }, [load, tick])

  if (loading) return <Spinner label="Loading earnings…" />
  if (!data) return <div className="page"><div className="empty">{error || 'No data.'}</div></div>

  const s = data.summary
  const commissionPct = Math.round((data.commissionRate || 0) * 100)
  const minimum = data.minimumPayout || 0
  const shortfall = Math.max(0, minimum - s.nextPayoutAmount)

  return (
    <div className="page">
      <div className="page-head">
        <h2>Earnings &amp; payouts</h2>
        <button className="btn btn-ghost" onClick={load}>Refresh</button>
      </div>

      {error && <div className="banner banner-rejected">{error}</div>}

      <div className="stat-row">
        <Stat value={formatPKR(s.netEarnings)} label="Net earnings" />
        <Stat value={formatPKR(s.paidOut)} label="Paid out" tone="green" />
        <Stat value={formatPKR(s.pendingPayoutAmount)} label="Payout in progress" tone={s.pendingPayoutAmount > 0 ? 'amber' : undefined} />
        <Stat value={formatPKR(s.nextPayoutAmount)} label="Next payout" />
        <Stat value={formatPKR(s.totalCommission)} label={`Platform commission (${commissionPct}%)`} />
        <Stat value={s.totalOrders} label="Paid deliveries" />
      </div>

      <div className={`banner ${s.nextPayoutEligible ? 'banner-approved' : 'banner-pending'}`}>
        {s.nextPayoutEligible
          ? `You have ${formatPKR(s.nextPayoutAmount)} ready for payout — the platform will process it.`
          : s.nextPayoutAmount > 0
            ? `${formatPKR(shortfall)} more needed to reach the minimum payout of ${formatPKR(minimum)}.`
            : 'Deliver orders to start earning. Payouts are generated by the platform.'}
      </div>

      <div className="grid-2-admin">
        <div className="card">
          <div className="card-head">
            <h3>Recent deliveries</h3>
            <span className="muted small">{commissionPct}% platform commission</span>
          </div>
          {data.earnings.length === 0 ? (
            <div className="empty">No completed deliveries yet.</div>
          ) : (
            <div className="table-wrap">
              <table className="table">
                <thead>
                  <tr>
                    <th>Order</th>
                    <th>Delivered</th>
                    <th>Delivery fee</th>
                    <th>Commission</th>
                    <th>You earn</th>
                  </tr>
                </thead>
                <tbody>
                  {data.earnings.map((r) => (
                    <tr key={r.orderId}>
                      <td className="mono">{r.orderNumber || '—'}</td>
                      <td>{fmtDate(r.deliveredAt)}</td>
                      <td>{formatPKR(r.deliveryFee)}</td>
                      <td className="muted">− {formatPKR(r.commission)}</td>
                      <td><strong>{formatPKR(r.net)}</strong></td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
          <p className="muted small">
            Commission is locked at the rate in effect when each order was delivered.
          </p>
        </div>

        <div className="card">
          <div className="card-head">
            <h3>Payout history</h3>
          </div>
          {data.payouts.length === 0 ? (
            <div className="empty">No payouts yet.</div>
          ) : (
            <div className="table-wrap">
              <table className="table">
                <thead>
                  <tr>
                    <th>Date</th>
                    <th>Orders</th>
                    <th>Amount</th>
                    <th>Status</th>
                  </tr>
                </thead>
                <tbody>
                  {data.payouts.map((p) => (
                    <tr key={p._id}>
                      <td>{fmtDate(p.paidAt || p.createdAt)}</td>
                      <td>{p.orderCount}</td>
                      <td><strong>{formatPKR(p.amount)}</strong></td>
                      <td>
                        <span className={`pill ${PAYOUT_PILL[p.status] || ''}`}>{p.status}</span>
                        {p.reference && <div className="muted small mono">{p.reference}</div>}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
          <div className="stat-row" style={{ gridTemplateColumns: '1fr 1fr', marginTop: 12 }}>
            <Stat value={formatPKR(s.nextPayoutAmount)} label="Unsettled earnings" />
            <Stat value={formatPKR(s.pendingPayoutAmount)} label="Awaiting payout" tone={s.pendingPayoutAmount > 0 ? 'amber' : undefined} />
          </div>
        </div>
      </div>
    </div>
  )
}
